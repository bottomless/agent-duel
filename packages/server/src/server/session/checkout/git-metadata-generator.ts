import type pino from "pino";
import { PaseoConfigSchema } from "@getpaseo/protocol/paseo-config-schema";
import { validateBranchSlug } from "@getpaseo/protocol/branch-slug";
import type { GitMetadataRequest, GitMetadataResult } from "../../agent/agent-sdk-types.js";
import type { WorkspaceGitService } from "../../workspace-git-service.js";
import { readPaseoConfigJson } from "../../../utils/paseo-config-file.js";

export interface PullRequestText {
  title: string;
  body: string;
}

/**
 * Generates a workspace's commit message and pull-request text from its git diff, the branch name
 * the Create branch dialog offers, and the title of a chat started with Battle off. The checkout
 * subsystem asks for the first three when the user left them blank; workspace naming asks for the
 * title. A commit or PR never fails for want of text: anything that goes wrong writing it answers a
 * fixed message instead. A branch name or a title is only an offer, so it answers null instead.
 */
export interface GitMetadataGenerator {
  generateCommitMessage(cwd: string): Promise<string>;
  generatePullRequestText(cwd: string, baseRef?: string): Promise<PullRequestText>;
  suggestBranchName(cwd: string, chatTitle: string | null): Promise<string | null>;
  suggestChatTitle(cwd: string, prompt: string): Promise<string | null>;
}

/**
 * Writes the text on Arena's summary model (`AgentManager.writeGitMetadata`). Injected so the
 * generator's diff rendering and fallbacks are unit-testable; null means nothing can write it.
 */
export interface GitMetadataWriter {
  write(
    cwd: string,
    request: GitMetadataRequest,
    signal: AbortSignal,
  ): Promise<GitMetadataResult | null>;
}

type GitMetadataDiffSource = Pick<WorkspaceGitService, "getCheckoutDiff" | "resolveRepoRoot">;
type CheckoutDiffOptions = Parameters<GitMetadataDiffSource["getCheckoutDiff"]>[1];
type CheckoutDiff = Awaited<ReturnType<GitMetadataDiffSource["getCheckoutDiff"]>>;

const PULL_REQUEST_FALLBACK_BODY = "Automated PR generated by Agent Duel.";

// The Arena route accepts 60,000 characters of changes (`arena-service/src/metadata.ts`); the
// engine trims whatever the file list adds past it.
const MAX_PATCH_CHARS = 60_000;
const WRITE_TIMEOUT_MS = 30_000;
const MAX_TITLE_PROMPT_CHARS = 4_000;

export function createGitMetadataGenerator(deps: {
  workspaceGitService: GitMetadataDiffSource;
  writer: GitMetadataWriter;
  logger: Pick<pino.Logger, "warn">;
}): GitMetadataGenerator {
  const { workspaceGitService, writer, logger } = deps;

  async function readChanges(cwd: string, diffOptions: CheckoutDiffOptions) {
    const diff = await workspaceGitService.getCheckoutDiff(cwd, diffOptions);
    const patch = truncatePatch(diff.diff, MAX_PATCH_CHARS);
    return {
      fileCount: diff.structured?.length ?? 0,
      changes: [renderFileList(diff.structured), "", patch || "(No diff available)"].join("\n"),
    };
  }

  async function write(
    cwd: string,
    request: GitMetadataRequest,
  ): Promise<GitMetadataResult | null> {
    const controller = new AbortController();
    let timer: ReturnType<typeof setTimeout> | undefined;
    const timeout = new Promise<never>((_, reject) => {
      timer = setTimeout(() => {
        controller.abort();
        reject(new Error(`Timed out after ${WRITE_TIMEOUT_MS}ms`));
      }, WRITE_TIMEOUT_MS);
    });
    try {
      return await Promise.race([writer.write(cwd, request, controller.signal), timeout]);
    } finally {
      clearTimeout(timer);
    }
  }

  return {
    async generateCommitMessage(cwd) {
      let fileCount = 0;
      try {
        const read = await readChanges(cwd, { mode: "uncommitted", includeStructured: true });
        fileCount = read.fileCount;
        const instructions = await readProjectInstructions(
          workspaceGitService,
          cwd,
          "commitMessage",
        );
        const result = await write(cwd, {
          kind: "commit_message",
          changes: read.changes,
          ...(instructions ? { instructions } : {}),
        });
        if (result && "message" in result) {
          return result.message;
        }
        logger.warn({ cwd }, "No commit message writer is available; using the fixed message");
      } catch (error) {
        logger.warn(
          { err: error, cwd },
          "Commit message generation failed; using the fixed message",
        );
      }
      return updateFilesMessage(fileCount);
    },

    async generatePullRequestText(cwd, baseRef) {
      let fileCount = 0;
      try {
        const read = await readChanges(cwd, { mode: "base", baseRef, includeStructured: true });
        fileCount = read.fileCount;
        const instructions = await readProjectInstructions(workspaceGitService, cwd, "pullRequest");
        const result = await write(cwd, {
          kind: "pull_request",
          changes: read.changes,
          ...(instructions ? { instructions } : {}),
        });
        if (result && "body" in result) {
          return { title: result.title, body: result.body || PULL_REQUEST_FALLBACK_BODY };
        }
        logger.warn({ cwd }, "No pull request writer is available; using the fixed text");
      } catch (error) {
        logger.warn(
          { err: error, cwd },
          "Pull request text generation failed; using the fixed text",
        );
      }
      return { title: updateFilesMessage(fileCount), body: PULL_REQUEST_FALLBACK_BODY };
    },

    // The branch goes on the checkout as it stands, so the chat's title and its uncommitted
    // changes say what it holds. With neither there is nothing to name it from.
    async suggestBranchName(cwd, chatTitle) {
      let changes: string | null = null;
      try {
        const read = await readChanges(cwd, { mode: "uncommitted", includeStructured: true });
        changes = read.fileCount > 0 ? read.changes : null;
      } catch (error) {
        logger.warn({ err: error, cwd }, "Could not read changes for a branch name suggestion");
      }
      const work = [chatTitle ? `Chat: ${chatTitle}` : null, changes].filter(Boolean).join("\n\n");
      if (!work) {
        return null;
      }
      try {
        const instructions = await readProjectInstructions(workspaceGitService, cwd, "branchName");
        const result = await write(cwd, {
          kind: "branch_name",
          changes: work,
          ...(instructions ? { instructions } : {}),
        });
        if (result && "branch" in result && validateBranchSlug(result.branch).valid) {
          return result.branch;
        }
        logger.warn({ cwd }, "No usable branch name suggestion");
      } catch (error) {
        logger.warn({ err: error, cwd }, "Branch name suggestion failed");
      }
      return null;
    },

    // A title needs only the start of the prompt, so a pasted log does not pay for its tail.
    async suggestChatTitle(cwd, prompt) {
      const source = prompt.trim().slice(0, MAX_TITLE_PROMPT_CHARS);
      if (!source) {
        return null;
      }
      try {
        const instructions = await readProjectInstructions(workspaceGitService, cwd, "title");
        const result = await write(cwd, {
          kind: "chat_title",
          changes: source,
          ...(instructions ? { instructions } : {}),
        });
        if (result && "title" in result && !("body" in result) && result.title.trim()) {
          return result.title.trim();
        }
        logger.warn({ cwd }, "No usable chat title");
      } catch (error) {
        logger.warn({ err: error, cwd }, "Chat title generation failed");
      }
      return null;
    },
  };
}

function updateFilesMessage(fileCount: number): string {
  if (fileCount === 0) return "Update files";
  return `Update ${fileCount} ${fileCount === 1 ? "file" : "files"}`;
}

// paseo.json `metadataGeneration.<key>.instructions`, edited in Project Settings, replaces the
// default style. The route places it in its own prompt; the contract around it is not editable.
async function readProjectInstructions(
  workspaceGitService: Pick<WorkspaceGitService, "resolveRepoRoot">,
  cwd: string,
  key: "title" | "commitMessage" | "pullRequest" | "branchName",
): Promise<string | undefined> {
  try {
    const repoRoot = await workspaceGitService.resolveRepoRoot(cwd);
    const config = PaseoConfigSchema.parse(readPaseoConfigJson(repoRoot));
    return config.metadataGeneration?.[key]?.instructions?.trim() || undefined;
  } catch {
    return undefined;
  }
}

function renderFileList(structured: CheckoutDiff["structured"]): string {
  if (!structured || structured.length === 0) {
    return "Files changed: (unknown)";
  }
  return [
    "Files changed:",
    ...structured.map((file) => {
      const changeType = diffChangeTypeFor(file);
      const status = file.status && file.status !== "ok" ? ` [${file.status}]` : "";
      return `${changeType}\t${file.path}\t(+${file.additions} -${file.deletions})${status}`;
    }),
  ].join("\n");
}

function truncatePatch(patch: string, maxPatchChars: number): string {
  if (patch.length <= maxPatchChars) {
    return patch;
  }
  return `${patch.slice(0, maxPatchChars)}\n\n... (diff truncated to ${maxPatchChars} chars)\n`;
}

function diffChangeTypeFor(file: { isNew?: boolean; isDeleted?: boolean }): "A" | "D" | "M" {
  if (file.isNew) return "A";
  if (file.isDeleted) return "D";
  return "M";
}
